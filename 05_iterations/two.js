//while
let index=0;
while (index<=10) {
    console.log(`value of index is ${index}`);
    index+=2;
}//0,2,4,6,8 and 10 gets printed

let myArray = ["flash","batman","superman"]
let arr = 0
while (arr<myArray.length) {
    console.log(`value is ${myArray[arr]}`);
    arr++;
}
//value is flash
//value is batman
//value is superman


//do-while loop'
let score = 1
do {
    console.log(`score is ${score}`)
    score++;
} while (score<=10);
//score from 1 to 10 gets printed

let points = 11
do {
    console.log(`points are ${points}`)
    score++;
} while (points<=10);//points are 11